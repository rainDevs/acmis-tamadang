  CONSTRAINT `uq_appointments_reference` UNIQUE (`reference_no`),
  INDEX `idx_appointments_slot` (`service_id`, `appointment_date`, `start_time`, `status`),
  INDEX `idx_appointments_status_date` (`status`, `appointment_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

