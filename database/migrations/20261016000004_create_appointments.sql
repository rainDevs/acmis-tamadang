CREATE TABLE `appointments` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `reference_no` VARCHAR(20) NOT NULL COMMENT 'Public reference, e.g. ACMIS-2026-XXXXXX; generated by API (TASK-010)',
  `service_id` BIGINT UNSIGNED NOT NULL,
  `appointment_date` DATE NOT NULL,
  `start_time` TIME NOT NULL COMMENT 'Must fall on the 30-minute grid; enforced by API (TASK-010)',
  `requester_name` VARCHAR(100) NOT NULL,
  `contact_number` VARCHAR(20) NOT NULL,
  `status` ENUM('pending','approved','rejected','cancelled','completed','no_show') NOT NULL DEFAULT 'pending',
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_appointments_service` FOREIGN KEY (`service_id`)
